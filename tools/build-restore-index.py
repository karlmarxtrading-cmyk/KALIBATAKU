"""Generate the offline adventure restore contract from the unchanged 1.2 bank and journey route."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / 'dist'
OUT = ROOT / 'src/data/journey-bank-index.js'


def generate():
    route = json.loads((ROOT / 'src/journey/v1/route.json').read_bytes())
    assert route['bank_content_version'] == '1.2.0'
    nodes = {n['competency_id']: n for n in route['nodes'] if n['active']}
    output = ['// Generated by tools/build-restore-index.py. Indexed only when a backup contains journey sessions.']
    levels = {}
    constraints = {}
    layouts = []
    for catalog in sorted((DIST / 'bank').glob('g*/l*.json'),key=lambda p:p.relative_to(DIST).parts):
        data = catalog.read_bytes()
        levels[catalog.relative_to(DIST).as_posix()] = hashlib.sha256(data).hexdigest()
        for cell in json.loads(data)['competencies']:
            if not cell['active']:
                continue
            node = nodes[cell['competency_id']]
            packages = []
            for i, entry in enumerate(cell['packages'], 1):
                assert entry['package_id'] == f"MM-G{node['grade']:02}-L{node['level']:02}-{node['operation']}-P{i:03}"
                assert entry['content_version'] == '1.2.0'
                assert bool(entry['form_id']) == (entry['purpose'] == 'assessment')
                packages.append([entry['purpose'], entry['question_count']])
            if packages not in layouts:
                layouts.append(packages)
            constraints[cell['competency_id']] = {
                'layout': layouts.index(packages),
                'coverage': min(12, node['teaching_unique']),
                'strategies': min(2, len(node['teaching_strategies'])),
                'shardSha256': node['occ']['sha256']
            }
    for name, value in [('levelHashes', levels), ('packageLayouts', layouts), ('nodeContracts', constraints)]:
        if isinstance(value, dict):
            body = '{\n' + ',\n'.join(f'  {json.dumps(k)}: {json.dumps(v)}' for k,v in value.items()) + '\n}'
        else:
            body = '[\n' + ',\n'.join('  ' + json.dumps(row) for row in value) + '\n]'
        output.append(f'export const {name} = {body};')
    return '\n'.join(output) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate()
    if args.check:
        if OUT.read_text() != result:
            raise SystemExit('Restore contract differs from bank and route')
        print('restore index verified')
    else:
        OUT.write_text(result, encoding="utf-8",newline="\n")

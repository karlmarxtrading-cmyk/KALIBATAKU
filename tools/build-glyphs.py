"""Extract the arithmetic glyph outlines used by the native SVG renderer.

Source font: src/assets/noto-Regular.woff (Noto Sans, SIL OFL, already shipped with the
app). Only digits, decimal separators, parentheses and the four operator symbols are
taken. U+2212 MINUS is absent from the subset, so it is drawn from the horizontal stem
of the plus glyph. Output is deterministic; `--check` fails when the committed module
differs from a fresh extraction.
"""
import argparse, hashlib, json, sys
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.transformPen import TransformPen

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'src/assets/noto-Regular.woff'
OUT = ROOT / 'src/math/glyphs.mjs'
CHARS = '0123456789,.()+×÷'


def path_for(font, gs, name):
    pen = SVGPathPen(gs, ntos=lambda v: str(round(v)))
    gs[name].draw(TransformPen(pen, (1, 0, 0, -1, 0, 0)))  # SVG y grows downwards
    bounds = BoundsPen(gs); gs[name].draw(bounds)
    return pen.getCommands(), bounds.bounds


def build():
    font = TTFont(FONT)
    cmap, gs = font.getBestCmap(), font.getGlyphSet()
    hmtx = font['hmtx']
    glyphs = {}
    for ch in CHARS:
        name = cmap[ord(ch)]
        d, box = path_for(font, gs, name)
        glyphs[ch] = {'w': hmtx[name][0], 'd': d, 'box': [round(v) for v in box] if box else None}
    # Minus: the horizontal bar of '+' spanning the full plus width.
    plus = glyphs['+']['box']
    # The bar of '+' is bounded by the two outline points on its left edge.
    from fontTools.pens.recordingPen import RecordingPen
    rec = RecordingPen(); gs[cmap[ord('+')]].draw(rec)
    ys = sorted({pt[1] for _, pts in rec.value for pt in pts if pt[0] == plus[0]})
    assert len(ys) == 2, ys
    stem = ys[1] - ys[0]; mid = (ys[0] + ys[1]) / 2
    top, bottom = round(-(mid + stem / 2)), round(-(mid - stem / 2))
    glyphs['−'] = {'w': glyphs['+']['w'], 'd': f"M{plus[0]} {top}H{plus[2]}V{bottom}H{plus[0]}Z", 'box': [plus[0], round(mid - stem / 2), plus[2], round(mid + stem / 2)]}
    data = {'source': 'Noto Sans 2.004 (src/assets/noto-Regular.woff), SIL Open Font License 1.1',
            'font_sha256': hashlib.sha256(FONT.read_bytes()).hexdigest(),
            'units_per_em': font['head'].unitsPerEm, 'ascent': font['hhea'].ascent, 'descent': font['hhea'].descent,
            'axis': mid, 'rule': stem, 'digit_height': glyphs['0']['box'][3],
            'glyphs': {k: {'w': v['w'], 'd': v['d']} for k, v in glyphs.items()}}
    body = ('// Generated by tools/build-glyphs.py. Do not edit by hand.\n'
            'export default ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
    return body


def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--check', action='store_true'); args = ap.parse_args()
    body = build()
    if args.check:
        if not OUT.is_file() or OUT.read_text() != body:
            print('glyphs.mjs differs from a fresh extraction', file=sys.stderr); return 1
        print('glyphs.mjs reproducible', hashlib.sha256(body.encode()).hexdigest()); return 0
    OUT.write_text(body); print('wrote', OUT.relative_to(ROOT), len(body), 'bytes'); return 0


if __name__ == '__main__':
    raise SystemExit(main())
